(ns net.willcohen.native.gen-handler
  "Build-time generator of a worker-router ModuleHandler module from fndefs
   and library overrides. It runs on the JVM or babashka, because a squint
   user-space macro cannot read consumer fndefs through a deps.edn
   :local/root."
  (:require [clojure.string :as str]))

(def ^:private required-override-keys
  [:overrides-import-path :runtime-import-path :exposed-methods])

(defn- check-required! [overrides]
  (doseq [k required-override-keys]
    (when (nil? (get overrides k))
      (throw (ex-info (str "gen-handler-source: missing required override key " k)
                      {:missing k :overrides-keys (vec (keys overrides))})))))

(defn- js-string-literal
  [s]
  (let [s (name s)]
    (str "\""
         (-> s
             (str/replace "\\" "\\\\")
             (str/replace "\"" "\\\""))
         "\"")))

(defn- js-string-array [coll]
  (str "[" (str/join ", " (map js-string-literal coll)) "]"))

(defn- destroy-fns-from-fndefs [fndefs]
  (->> fndefs
       (filter (fn [[_ v]] (:destroy? v)))
       (map (comp name first))
       sort
       vec))

(def ^:private default-preamble
  (str "// Generated by clj-native gen-handler-source. Do not edit by hand;\n"
       "// changes will be overwritten on the next bb gen-handler run.\n"
       "//\n"
       "// Wires a hand-written overrides module (init, methods, fingerprint)\n"
       "// into clj-native's handler runtime, applying the busy/destroy\n"
       "// classification computed from the consumer's fndefs."))

(defn gen-handler-source
  "Return the source of a JS handler module.

   fndefs     {fn-key {:rettype :argtypes :busy? :destroy? ...}}.
   overrides  Keys:
     :overrides-import-path  Required. Path of the overrides .mjs.
     :runtime-import-path    Required. Path of the handler runtime.
     :exposed-methods        Required. Method keywords, each mapped to
                             overrides.methods.<name>.
     :busy-methods           Subset of :exposed-methods, disjoint from
                             :destroy-methods. Default [].
     :destroy-methods        Subset of :exposed-methods. Default [].
     :destroy-fns            C fn names. Default: fndefs keys with :destroy?.
     :fingerprint-fields     Init-arg names. Emits a byteLengthFingerprint
                             in place of overrides.fingerprint.
     :fingerprint-prefix     Fingerprint label for re-init errors. Needs
                             :fingerprint-fields.
     :preamble               Text for the top of the output, with its own
                             // markers.

   The busy and destroy classes affect trace fields only, because the
   runtime queue is serial. Prefer :fingerprint-fields: the bundler inlines
   this module but not the overrides module, so an overrides module that
   imports the runtime gets a second copy with its own logging state."
  [fndefs overrides]
  (check-required! overrides)
  (let [{:keys [overrides-import-path runtime-import-path
                exposed-methods busy-methods destroy-methods
                destroy-fns fingerprint-fields fingerprint-prefix
                preamble]} overrides
        busy-methods (or busy-methods [])
        destroy-methods (or destroy-methods [])
        destroy-fns (or destroy-fns (destroy-fns-from-fndefs fndefs))
        generated-fingerprint? (seq fingerprint-fields)
        method-bindings (->> exposed-methods
                             (map (fn [m]
                                    (let [n (name m)]
                                      (str "  " n ": overrides.methods." n ","))))
                             (str/join "\n"))]
    (str
     (or preamble default-preamble) "\n\n"
     "import { makeHandler"
     (when generated-fingerprint? ", byteLengthFingerprint")
     " } from '" runtime-import-path "';\n"
     "import * as overrides from '" overrides-import-path "';\n"
     "\n"
     "// Method classification. The handler runtime header says what it does.\n"
     "const busyMethods = " (js-string-array busy-methods) ";\n"
     "const destroyMethods = " (js-string-array destroy-methods) ";\n"
     "\n"
     "// C fnNames from the fndefs :destroy? flags. Nothing reads this.\n"
     "const destroyFns = " (js-string-array destroy-fns) ";\n"
     "\n"
     "const methods = {\n"
     method-bindings "\n"
     "};\n"
     "\n"
     (when generated-fingerprint?
       (str "// Init-arg fields this handler is cached on. Bytes contribute their\n"
            "// length, so a database costs one number rather than its contents.\n"
            "const fingerprint = byteLengthFingerprint(\n"
            "  " (js-string-array (map name fingerprint-fields)) ",\n"
            "  " (if fingerprint-prefix (str "'" fingerprint-prefix "'") "null") ",\n"
            ");\n"
            "\n"))
     "export const create = makeHandler({\n"
     "  init: overrides.init,\n"
     "  methods,\n"
     "  busyMethods,\n"
     "  destroyMethods,\n"
     "  fingerprint: " (if generated-fingerprint? "fingerprint" "overrides.fingerprint") ",\n"
     "});\n"
     "\n"
     "export default create;\n"
     "export { create as handler };\n"
     "export { destroyFns };\n"
     "\n"
     "// Module-level teardown for worker-router's coordinator shutdown, which\n"
     "// invokes `mod.destroy` (see worker-bootstrap loadAllHandlers) once per\n"
     "// worker when the pool terminates. Forwards to the overrides module's\n"
     "// destroy when it exports one, else undefined (worker-router guards with\n"
     "// `typeof mod.destroy === 'function'`). This is where a handler closes\n"
     "// nested resources the emscripten Module holds open, such as the\n"
     "// http-bridge fetch worker.\n"
     "//\n"
     "// A handler that exports no destroy is not a leak on node 26: terminate()\n"
     "// reaps a nested worker_thread, measured with sixteen pool workers and\n"
     "// requests in flight. Export one to close the resource on purpose.\n"
     "export const destroy = overrides.destroy;\n")))

(defn write-handler!
  "Write the gen-handler-source output to `out-path`, a string or File.
   Returns the path as a string."
  [fndefs overrides out-path]
  (let [src (gen-handler-source fndefs overrides)]
    (spit out-path src)
    (str out-path)))
